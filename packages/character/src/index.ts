/**
 * 모드별 대화 정책.
 * 호칭·말 거는 방식·섹션 이름처럼 방송과 1:1 대화에서 달라지는 것만 여기에 둔다.
 */
export type ConversationPolicy = {
  mode: ConversationMode;
  /** 프롬프트 [대화 정책] 섹션 제목에 붙는 이름. */
  title: string;
  /** [대화 정책] 섹션에 그대로 들어가는 문장. */
  rules: readonly string[];
  /** 출력 규칙의 "reply는 N자 이내의 한국어 존댓말 ○○이다"에 들어갈 문장 수. */
  replySentences: string;
  /** 최근 대화에서 상대와 보리를 가리키는 이름. */
  speakerLabels: { user: string; bori: string };
  sectionTitles: {
    /** 서버가 계산한 현재 상황(경과 시간, 답변 수 등). */
    status: string;
    /** 최근 대화 창 밖으로 밀려난 흐름의 누적 요약. */
    summary: string;
    /** 이번에 답할 입력. */
    input: string;
  };
  /**
   * 접근 가능한 기억이 하나도 없을 때 [기억] 섹션에 넣는 문장.
   * 섹션을 지우면 모델이 "기억이 없다"와 "찾아보지 않았다"를 구분하지 못해 지어낸다.
   */
  noMemoryLine: string;
  /**
   * 규칙 응답(인사·칭찬·음악·게임 등 고정 문장)을 쓸지.
   * 방송은 빠른 반응을 위해 쓰고, 1:1은 쓰지 않고 LLM이 답한다.
   */
  ruleReplies: boolean;
  /**
   * 위험 주제를 막았을 때의 거절 문장. 비어 있으면 무반응한다.
   * 방송은 무반응하고, 1:1은 상대가 기다리고 있으므로 짧게 거절한다.
   */
  refusalReplies: readonly string[];
  /**
   * LLM을 쓸 수 없거나 실패했을 때의 문장. null이면 서버의 규칙 폴백 문장을 쓴다.
   * 서버 폴백 문장에는 "여러분" 같은 방송 호칭이 있어 1:1은 따로 둔다.
   */
  fallbackReplies: readonly string[] | null;
};

